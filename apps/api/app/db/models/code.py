"""Indexed code chunks (vector + full-text), chat, webhook deliveries and the job queue."""

import uuid
from datetime import datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Computed,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    Uuid,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, CreatedAtMixin, TimestampMixin, UuidPkMixin, check_in
from app.db.constants import EMBEDDING_DIM
from app.db.models.enums import JobStatus, MessageRole


class CodeChunk(UuidPkMixin, TimestampMixin, Base):
    __tablename__ = "code_chunks"

    repository_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("repositories.id", ondelete="CASCADE")
    )
    path: Mapped[str] = mapped_column(String(1000))
    language: Mapped[str | None] = mapped_column(String(50))
    start_line: Mapped[int] = mapped_column(Integer)
    end_line: Mapped[int] = mapped_column(Integer)
    content: Mapped[str] = mapped_column(Text)
    embedding: Mapped[Any] = mapped_column(Vector(EMBEDDING_DIM))
    # Generated by Postgres from `content`, always in sync, never written by us. The 'simple'
    # configuration does no stemming or stop words, which suits identifiers like `get_user_id`.
    tsv: Mapped[Any] = mapped_column(
        TSVECTOR, Computed("to_tsvector('simple', content)", persisted=True)
    )
    commit_sha: Mapped[str] = mapped_column(String(40))

    __table_args__ = (
        # Re-index a changed file: "delete/replace all chunks of (repo, path)".
        Index("ix_code_chunks_repository_id_path", "repository_id", "path"),
        # Approximate nearest-neighbour search by cosine distance. The operator class must
        # match the query operator (<=>) or Postgres will not use the index.
        Index(
            "ix_code_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},  # pgvector defaults, explicit
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
        # Inverted index for `tsv @@ websearch_to_tsquery(...)`.
        Index("ix_code_chunks_tsv", "tsv", postgresql_using="gin"),
    )


class ChatSession(UuidPkMixin, TimestampMixin, Base):
    __tablename__ = "chat_sessions"

    # Chat data is wiped with its repository (hard delete) and by the uninstall purge job.
    repository_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("repositories.id", ondelete="CASCADE")
    )
    # SET NULL: deleting a user must not silently erase the conversation record.
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    title: Mapped[str | None] = mapped_column(String(255))

    __table_args__ = (
        Index("ix_chat_sessions_repository_id", "repository_id"),
        Index("ix_chat_sessions_user_id", "user_id"),
    )


class ChatMessage(UuidPkMixin, CreatedAtMixin, Base):
    __tablename__ = "chat_messages"

    session_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("chat_sessions.id", ondelete="CASCADE")
    )
    role: Mapped[str] = mapped_column(String(20))
    content: Mapped[str] = mapped_column(Text)
    # An array, not a join table, because chunk rows are replaced on re-index: a dangling id
    # just means "that chunk has since changed", and an FK would block re-indexing.
    cited_chunk_ids: Mapped[list[uuid.UUID]] = mapped_column(
        ARRAY(Uuid), server_default=text("'{}'::uuid[]")
    )

    __table_args__ = (
        check_in("role", MessageRole),
        Index("ix_chat_messages_session_id_created_at", "session_id", "created_at"),
    )


class WebhookDelivery(UuidPkMixin, CreatedAtMixin, Base):
    __tablename__ = "webhook_deliveries"

    # X-GitHub-Delivery. The UNIQUE constraint is what makes webhook intake idempotent:
    # a redelivery fails the insert, and the handler answers 200 without enqueuing again.
    delivery_id: Mapped[str] = mapped_column(String(64), unique=True)
    event: Mapped[str] = mapped_column(String(50))
    action: Mapped[str | None] = mapped_column(String(50))
    # The payload is deliberately NOT stored: it contains PR titles and repo details we have
    # no need to keep.


class Job(UuidPkMixin, TimestampMixin, Base):
    __tablename__ = "jobs"

    type: Mapped[str] = mapped_column(String(50))
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))
    status: Mapped[str] = mapped_column(String(20), server_default=JobStatus.QUEUED.value)
    attempts: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    max_attempts: Mapped[int] = mapped_column(Integer, server_default=text("5"))
    run_after: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=text("now()")
    )
    locked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_error: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (
        check_in("status", JobStatus),
        # Partial indexes: only the rows a query can actually want. The claim query scans
        # queued jobs by run_after; stale-lock recovery scans running jobs by locked_at.
        # Finished jobs (the vast majority over time) are in neither index.
        Index(
            "ix_jobs_claimable",
            "run_after",
            postgresql_where=text("status = 'queued'"),
        ),
        Index(
            "ix_jobs_running_locked_at",
            "locked_at",
            postgresql_where=text("status = 'running'"),
        ),
    )
