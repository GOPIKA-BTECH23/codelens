"""Declarative base, constraint naming convention and the timestamp mixins."""

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import CheckConstraint, DateTime, MetaData, Uuid, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Explicit names for every constraint. Without this Postgres invents names, and Alembic
# cannot reliably drop or alter a constraint it never named (breaks downgrades).
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for every model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UuidPkMixin:
    """UUID primary key generated by Postgres, so rows inserted by raw SQL get one too."""

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid, primary_key=True, server_default=text("gen_random_uuid()")
    )


class CreatedAtMixin:
    """created_at, set by the database clock."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )


class TimestampMixin(CreatedAtMixin):
    """created_at plus updated_at.

    updated_at is refreshed by SQLAlchemy on every UPDATE it emits (ORM and Core `update()`),
    using the database clock. Raw SQL written by hand bypasses this, so queue code uses
    SQLAlchemy statements, and a test pins the behaviour.
    """

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


def check_in(column: str, values: type[StrEnum], name: str | None = None) -> CheckConstraint:
    """CHECK (column IN (...enum values...)).

    We use VARCHAR + CHECK instead of native Postgres enums: adding a value to a native enum
    needs ALTER TYPE (awkward inside a transaction, impossible to remove), a CHECK is a
    one-line migration.
    """
    allowed = ", ".join(f"'{member.value}'" for member in values)
    return CheckConstraint(f"{column} IN ({allowed})", name=name or column)
